#!/usr/bin/env python3
"""tools/gen/gen_emojidata.py -- the emoji the picker and Character Map list.

Writes data/usr/share/unicode/emoji, read by userland/libs/base/uemojidata.c:

    # comment lines
    @Smileys & Emotion        a group, in Unicode's (CLDR's) order
    1F600;grinning face       an entry: its code points, then its CLDR name
    2764 FE0F;red heart       ...with U+FE0F where the fully-qualified form has one

THE INPUT IS VENDORED, NOTHING IS FETCHED: tools/gen/data/emoji-test.txt is
Unicode's emoji-test.txt (UTS #51), at the version its header names. It is
Unicode, Inc.'s data under the Unicode License v3, whose notice travels as
data/licenses/unicode.txt.

EVERY EMOJI THE FACE DRAWS AS ONE GLYPH: a character (with U+FE0F), or a
ZWJ sequence, flag or keycap the face's `ccmp` ligatures make one -- read
with tools/lib/otl.py, the reader otl_hostcheck.py holds to the C. Only
fully-qualified entries are kept (each once) and the Component group is left
out. A SKIN-TONED variant is not an entry: the medium one becomes its base
entry's third field, a template with '~' where the tone goes, kept when the
face draws all five tones as one glyph -- what the picker's right-click
variants are made from. Re-run when either input changes; the output is
deterministic.

    python3 tools/gen/gen_emojidata.py [--out PATH] [--check]

`--check` regenerates in memory and fails if the committed file differs.
"""
import argparse
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../lib"))
import toolpath  # noqa: E402,F401 -- every tools/ folder on sys.path
import otl  # noqa: E402

ROOT = toolpath.REPO
SRC = os.path.join(ROOT, "tools", "gen", "data", "emoji-test.txt")
FACE = os.path.join(ROOT, "data", "fonts", "fallback", "twemoji.ttf")
OUT = os.path.join(ROOT, "data", "usr", "share", "unicode", "emoji")
DROPPED_GROUPS = ("Component",)
LINE = re.compile(r"^([0-9A-F ]+?)\s*;\s*([a-z-]+)\s*#\s*\S+\s+E[0-9.]+\s+(.*)$")


TONES = (0x1F3FB, 0x1F3FC, 0x1F3FD, 0x1F3FE, 0x1F3FF)
MEDIUM = ": medium skin tone"


def one_glyph(f, cps):
    """Whether the emoji face draws `cps` as ONE glyph: a single character
    (with U+FE0F), or a sequence its `ccmp` ligatures make one."""
    gids = [f.gid(c) for c in cps]
    if not all(gids):
        return False
    if len(cps) == 1 or (len(cps) == 2 and cps[1] == 0xFE0F):
        return True
    return len(f.ligate(gids, "ccmp")) == 1


def generate(src=SRC, face=FACE):
    f = otl.Font(face)
    version, group, kept, dropped = "?", None, 0, 0
    groups, by_name, toned = [], {}, {}
    for raw in open(src, encoding="utf-8"):
        raw = raw.rstrip("\n")
        m = re.match(r"^# Version: (\S+)", raw)
        if m:
            version = m.group(1)
        m = re.match(r"^# group: (.*)$", raw)
        if m:
            group = m.group(1).strip()
            continue
        m = LINE.match(raw)
        if not m or group in DROPPED_GROUPS or m.group(2) != "fully-qualified":
            continue
        cps = [int(x, 16) for x in m.group(1).split()]
        name = m.group(3).strip()
        if any(c in TONES for c in cps):
            # A TONED VARIANT is not an entry of its own: the medium one is
            # the template the picker's variants are made from ("~" where a
            # tone goes), kept when the face draws all five as one glyph.
            if name.endswith(MEDIUM) and ":" not in name[:-len(MEDIUM)]:
                tpl = ["~" if c == 0x1F3FD else c for c in cps]
                if all(one_glyph(f, [t if c == "~" else c for c in tpl]) for t in TONES):
                    toned[name[:-len(MEDIUM)]] = tpl
            continue
        if not one_glyph(f, cps):
            dropped += 1
            continue
        if not groups or groups[-1][0] != group:
            groups.append((group, []))
        groups[-1][1].append((cps, name))
        by_name[name] = cps
        kept += 1
    out = [
        f"# GENERATED by tools/gen/gen_emojidata.py from Unicode's emoji-test.txt {version}",
        "# (tools/gen/data/emoji-test.txt), Unicode License v3 (data/licenses/unicode.txt).",
        "# Do not edit: re-run the tool. Every emoji the emoji face draws as one glyph;",
        "# a third field is its skin-tone template, '~' where the tone goes.",
    ]
    ntoned = 0
    for name, entries in groups:
        out.append("@" + name)
        for cps, nm in entries:
            line = " ".join("%04X" % c for c in cps) + ";" + nm
            if nm in toned:
                line += ";" + " ".join("~" if c == "~" else "%04X" % c for c in toned[nm])
                ntoned += 1
            out.append(line)
    return "\n".join(out) + "\n", version, kept, dropped, len(groups), ntoned


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--check", action="store_true", help="fail if the committed file is stale")
    args = ap.parse_args()
    text, version, kept, dropped, ngroups, ntoned = generate()
    what = (f"emoji {version}: {kept} entries in {ngroups} groups, {ntoned} with skin tones, "
            f"{dropped} the face does not draw as one glyph left out")
    if args.check:
        with open(args.out, encoding="utf-8") as fh:
            if fh.read() != text:
                print(f"gen_emojidata: {args.out} is stale -- re-run tools/gen/gen_emojidata.py")
                return 1
        print(f"gen_emojidata: {args.out} current ({what})")
        return 0
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"gen_emojidata: wrote {args.out} ({what})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
