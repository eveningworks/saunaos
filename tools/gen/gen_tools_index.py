#!/usr/bin/env python3
"""Regenerate docs/tools.md's folder index: every tool, by folder, in one line each.

The line is the tool's own docstring (or a shell script's first comment),
so the index is DERIVED and cannot go stale -- `--check`, run by
check_docs.py, fails when a tool was added, moved, deleted or re-described
and this was not re-run. The full entries live in docs/tools/<folder>.md.

    python3 tools/gen/gen_tools_index.py           # rewrite the section
    python3 tools/gen/gen_tools_index.py --check   # exit 1 if stale
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../lib"))
import toolpath  # noqa: E402

DOC = os.path.join(toolpath.REPO, "docs", "tools.md")
BEGIN = "<!-- BEGIN folder index: generated by tools/gen/gen_tools_index.py -- do not edit -->"
END = "<!-- END folder index -->"


def render():
    by = {}
    for name, path in toolpath.all_tools().items():
        by.setdefault(os.path.relpath(os.path.dirname(path), toolpath.TOOLS), []).append((name, path))
    out = [BEGIN, ""]
    for folder, role in toolpath.FOLDERS:
        ref = "tools/" + folder.replace("/", "-") + ".md"
        out.append(f"### `tools/{folder}/` -- {role}")
        out.append("")
        out.append(f"Full entries: [`docs/{ref}`]({ref}).")
        out.append("")
        for name, path in sorted(by.pop(folder, [])):
            line = toolpath.summary(path).rstrip(".")
            out.append(f"- `{name}` -- {line}" if line else f"- `{name}`")
        out.append("")
    if by:
        raise SystemExit(f"gen_tools_index: folders missing from toolpath.FOLDERS: {sorted(by)}")
    out.append(END)
    return "\n".join(out)


def main():
    text = open(DOC, encoding="utf-8").read()
    if BEGIN not in text or END not in text:
        sys.exit(f"gen_tools_index: {DOC} has no {BEGIN!r} ... {END!r} section")
    a, b = text.index(BEGIN), text.index(END) + len(END)
    new = text[:a] + render() + text[b:]
    if "--check" in sys.argv[1:]:
        if new != text:
            print("gen_tools_index: docs/tools.md's folder index is stale -- "
                  "run tools/gen/gen_tools_index.py")
            return 1
        return 0
    if new != text:
        with open(DOC, "w", encoding="utf-8") as f:
            f.write(new)
        print("gen_tools_index: docs/tools.md rewritten")
    return 0


if __name__ == "__main__":
    sys.exit(main())
