#!/usr/bin/env python3
"""tools/gen/gen_emoji.py -- which characters are drawn as EMOJI by default.

Writes userland/libs/base/uemoji_table.h, the ranges whose
Emoji_Presentation property is Yes, merged and sorted for a binary search
in userland/libs/base/uemoji.h. The text path uses it to send such a
character to the emoji face first (U+2B50 is a coloured star, U+2605 a
text one); U+FE0F after any character asks for the same, U+FE0E for text.

THE SOURCE IS ON THIS MACHINE, NOTHING IS FETCHED: Python's `unicodedata`
has no emoji properties, but Perl's regex engine does (`\\p{Emoji_Presentation}`,
its own copy of Unicode's emoji-data.txt, at the version printed into the
header). It is Unicode, Inc.'s data under the Unicode License v3, whose
notice travels as data/licenses/unicode.txt. Re-run when a newer Perl
brings a newer Unicode; the output is deterministic.

    python3 tools/gen/gen_emoji.py [--out PATH] [--check]

`--check` regenerates in memory and fails if the committed file differs.
"""
import argparse
import os
import subprocess
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../lib"))
import toolpath  # noqa: E402,F401 -- every tools/ folder on sys.path
ROOT = toolpath.REPO
OUT = os.path.join(ROOT, "userland", "libs", "base", "uemoji_table.h")

# Prints "VERSION" then one "LO HI" line per merged range, in hex.
PERL = r'''
use Unicode::UCD;
print Unicode::UCD::UnicodeVersion(), "\n";
my ($lo, $prev);
for my $c (0 .. 0x10FFFF) {
    next if $c >= 0xD800 && $c <= 0xDFFF;
    if (chr($c) =~ /\p{Emoji_Presentation}/) {
        if (defined $prev && $c == $prev + 1) { $prev = $c; next; }
        printf("%X %X\n", $lo, $prev) if defined $lo;
        $lo = $prev = $c;
    }
}
printf("%X %X\n", $lo, $prev) if defined $lo;
'''


def generate():
    r = subprocess.run(["perl", "-e", PERL], capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"gen_emoji: perl failed: {r.stderr}")
    lines = r.stdout.split("\n")
    version, ranges = lines[0].strip(), [tuple(int(x, 16) for x in ln.split()) for ln in lines[1:] if ln.strip()]
    body = [
        f"// GENERATED by tools/gen/gen_emoji.py from Unicode {version}'s Emoji_Presentation",
        "// property (Perl's copy of emoji-data.txt), Unicode License v3",
        "// (data/licenses/unicode.txt). Do not edit: re-run the tool. Included by",
        "// base/uemoji.h only.",
        "#ifndef ULIB_UEMOJI_TABLE_H",
        "#define ULIB_UEMOJI_TABLE_H",
        "#include <stdint.h>",
        "",
        "static const uint32_t UEMOJI_PRESENTATION[][2] = {",
    ]
    body += [f"    {{ 0x{lo:05X}, 0x{hi:05X} }}," for lo, hi in ranges]
    body += ["};", "", "#endif", ""]
    return "\n".join(body), version, len(ranges)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--check", action="store_true", help="fail if the committed table is stale")
    args = ap.parse_args()
    text, version, n = generate()
    if args.check:
        with open(args.out) as fh:
            if fh.read() != text:
                print(f"gen_emoji: {args.out} is stale -- re-run tools/gen/gen_emoji.py")
                return 1
        print(f"gen_emoji: {args.out} current (Unicode {version}, {n} ranges)")
        return 0
    with open(args.out, "w") as fh:
        fh.write(text)
    print(f"gen_emoji: wrote {args.out} (Unicode {version}, {n} ranges)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
