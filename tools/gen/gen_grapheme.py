#!/usr/bin/env python3
"""tools/gen/gen_grapheme.py -- the Unicode tables text is segmented and composed by.

Writes two headers, both DATA ONLY and deterministic:

  kernel/include/api/kgrapheme_table.h
      Every code point's Grapheme_Cluster_Break class (UAX #29) that is not
      Other, plus Extended_Pictographic, as sorted ranges for a binary
      search in kernel/lib/kgrapheme.c -- what decides that a family emoji,
      a flag or a letter with its accents is ONE character to step over.
      Hangul LV/LVT syllables are left out: kgrapheme.c computes them.
  userland/libs/base/ucompose_table.h
      Every canonical COMPOSITION of a pair (base, combining mark) ->
      precomposed character, Unicode's composition exclusions left out, for
      base/ucompose.c: a decomposed "e + U+0301" is drawn as the face's own
      U+00E9.

THE SOURCES ARE ON THIS MACHINE, NOTHING IS FETCHED: Perl's regex engine
carries the break properties (`\\p{Grapheme_Cluster_Break=Extend}`,
`\\p{Extended_Pictographic}`), Python's `unicodedata` the decompositions --
each at the version printed into its header. Unicode, Inc.'s data under the
Unicode License v3, whose notice travels as data/licenses/unicode.txt.
Re-run when a newer Perl or Python brings a newer Unicode.

    python3 tools/gen/gen_grapheme.py [--check]

`--check` regenerates in memory and fails if a committed file differs.
"""
import argparse
import os
import subprocess
import sys
import unicodedata

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../lib"))
import toolpath  # noqa: E402,F401 -- every tools/ folder on sys.path

ROOT = toolpath.REPO
GB_OUT = os.path.join(ROOT, "kernel", "include", "api", "kgrapheme_table.h")
COMPOSE_OUT = os.path.join(ROOT, "userland", "libs", "base", "ucompose_table.h")

# kgrapheme.h's enum, in its order. Perl's property value names.
CLASSES = ["CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator", "Prepend", "SpacingMark",
           "L", "V", "T"]
PERL = r"""
use strict; use Unicode::UCD;
print "V ", Unicode::UCD::UnicodeVersion(), "\n";
my @props = (%s);
for my $c (0 .. 0x10FFFF) {
    next if $c >= 0xD800 && $c <= 0xDFFF;
    next if $c >= 0xAC00 && $c <= 0xD7A3;   # LV/LVT: computed
    my $s = chr($c);
    my $k = -1;
    for my $i (0 .. $#props) { if ($s =~ $props[$i]) { $k = $i; last; } }
    if ($k < 0 && $s =~ /\p{Extended_Pictographic}/) { $k = scalar(@props); }
    print "$c $k\n" if $k >= 0;
}
""" % ", ".join(f"qr/\\p{{Grapheme_Cluster_Break={c}}}/" for c in CLASSES)


def gb_ranges():
    out = subprocess.run(["perl", "-e", PERL], capture_output=True, text=True, check=True).stdout.split("\n")
    version = out[0].split()[1]
    ranges = []
    for line in out[1:]:
        if not line:
            continue
        c, k = map(int, line.split())
        if ranges and ranges[-1][1] == c - 1 and ranges[-1][2] == k:
            ranges[-1][1] = c
        else:
            ranges.append([c, c, k])
    return version, ranges


def gb_header():
    version, ranges = gb_ranges()
    names = [f"KGB_{c.upper()}" if c != "Regional_Indicator" else "KGB_RI" for c in CLASSES] + ["KGB_EP"]
    lines = [
        "// GENERATED by tools/gen/gen_grapheme.py -- do not edit; re-run it.",
        f"// Unicode {version}'s Grapheme_Cluster_Break classes (UAX #29) and",
        "// Extended_Pictographic, from Perl's Unicode::UCD; Unicode License v3",
        "// (data/licenses/unicode.txt). Hangul LV/LVT syllables are not here:",
        "// kgrapheme.c computes them. One row per range: first, last, class.",
        "#ifndef KGRAPHEME_TABLE_H",
        "#define KGRAPHEME_TABLE_H",
        "#include <stdint.h>",
        "",
        f"#define KGRAPHEME_UNICODE \"{version}\"",
        "",
        "static const struct { uint32_t lo, hi; uint8_t cls; } kgrapheme_ranges[] = {",
    ]
    for lo, hi, k in ranges:
        lines.append(f"    {{ 0x{lo:05X}, 0x{hi:05X}, {names[k]} }},")
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def compose_pairs():
    pairs = []
    for c in range(0x10FFFF + 1):
        d = unicodedata.decomposition(chr(c))
        if not d or d.startswith("<"):
            continue
        parts = [int(x, 16) for x in d.split()]
        if len(parts) != 2:
            continue
        # A composition exclusion (or a singleton target) never recomposes:
        # NFC of the pair is not `c`.
        if unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) != chr(c):
            continue
        pairs.append((parts[0], parts[1], c))
    return sorted(pairs)


def compose_header():
    pairs = compose_pairs()
    lines = [
        "// GENERATED by tools/gen/gen_grapheme.py -- do not edit; re-run it.",
        f"// Unicode {unicodedata.unidata_version}'s canonical compositions of a PAIR, from Python's",
        "// unicodedata, composition exclusions left out; Unicode License v3",
        "// (data/licenses/unicode.txt). Sorted by (first, second) for a binary search.",
        "#ifndef UCOMPOSE_TABLE_H",
        "#define UCOMPOSE_TABLE_H",
        "#include <stdint.h>",
        "",
        "static const struct { uint32_t first, second, composed; } ucompose_pairs[] = {",
    ]
    for a, b, c in pairs:
        lines.append(f"    {{ 0x{a:05X}, 0x{b:05X}, 0x{c:05X} }},")
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if a committed table differs")
    args = ap.parse_args()
    bad = 0
    for path, text in ((GB_OUT, gb_header()), (COMPOSE_OUT, compose_header())):
        rel = os.path.relpath(path, ROOT)
        if args.check:
            cur = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
            if cur != text:
                print(f"gen_grapheme: {rel} is stale -- run tools/gen/gen_grapheme.py")
                bad += 1
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
            print(f"gen_grapheme: wrote {rel} ({text.count(chr(10))} lines)")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
