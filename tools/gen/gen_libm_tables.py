#!/usr/bin/env python3
"""tools/gen/gen_libm_tables.py -- tolibc's maths constants, to the last bit.

Writes userland/libs/libc/math_tables.h: the bits of 2/pi that the
Payne-Hanek argument reduction multiplies by (enough for the largest long
double, 2^16384), and the long double constants -- pi/2, ln 2 and log2(e)
split into pieces -- that no decimal literal states exactly.

Computed here from INTEGERS ALONE (Machin's formula for pi, the series
sum 1/(k 2^k) for ln 2), with no third-party module, so the table can be
re-derived anywhere and checked rather than trusted. The first words of
2/pi are fdlibm's well-known 0xA2F9836E4E44..., which the script asserts.

    python3 tools/gen/gen_libm_tables.py [--check]

--check regenerates in memory and fails if the committed file differs.
"""
import argparse
import os
import sys
from fractions import Fraction as Fr

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../lib"))
import toolpath  # noqa: E402,F401 -- every tools/ folder on sys.path

REPO = toolpath.REPO
OUT = os.path.join(REPO, "userland/libs/libc/math_tables.h")
WORDS = 264          # 2/pi to 16,896 bits: the largest long double needs 259


def atan_inv(n, bits):
    """atan(1/n) * 2^bits, truncated."""
    x = (1 << bits) // n
    s, k, sign = x, 1, -1
    while x:
        x //= n * n
        k += 2
        s += sign * (x // k)
        sign = -sign
    return s


def pi_fixed(bits):
    g = bits + 64
    return (16 * atan_inv(5, g) - 4 * atan_inv(239, g)) >> 64


def ln2_fixed(bits):
    g = bits + 64
    s, k, t = 0, 1, (1 << g) >> 1
    while t:
        s += t // k
        k += 1
        t >>= 1
    return s >> 64


def round_bits(v, p):
    """Fraction v rounded to p significant bits, nearest-even."""
    if v < 0:
        return -round_bits(-v, p)
    e = 0
    while v >= 2 ** (e + 1):
        e += 1
    while v < 2 ** e:
        e -= 1
    scaled = v * Fr(2) ** (p - 1 - e)
    fl = scaled.numerator // scaled.denominator
    rem = scaled - fl
    if rem > Fr(1, 2) or (rem == Fr(1, 2) and fl % 2):
        fl += 1
    return Fr(fl) / Fr(2) ** (p - 1 - e)


def ld_hex(v):
    """A long double hex literal for a Fraction exact in 64 bits."""
    sign = "-" if v < 0 else ""
    v = abs(v)
    e = 0
    while v >= 2 ** (e + 1):
        e += 1
    while v < 2 ** e:
        e -= 1
    m = v * Fr(2) ** (63 - e)
    assert m.denominator == 1, v
    return "%s0x%016xp%dL" % (sign, m.numerator, e - 63)


def split(v, widths):
    """v as a sum of pieces, each rounded to the given width in bits."""
    out = []
    for w in widths:
        piece = round_bits(v, w)
        out.append(piece)
        v -= piece
    return out


def generate():
    bits = 64 * WORDS
    prec = bits + 256
    pi = Fr(pi_fixed(prec), 1 << prec)
    ln2 = Fr(ln2_fixed(prec), 1 << prec)
    two_over_pi = (2 << (prec + bits)) // pi_fixed(prec)   # (2/pi) * 2^bits
    words = [(two_over_pi >> (64 * (WORDS - 1 - i))) & (2 ** 64 - 1) for i in range(WORDS)]
    assert words[0] == 0xA2F9836E4E441529, hex(words[0])

    pio2 = split(pi / 2, (64, 64))
    # ln 2 with its first piece SHORT (48 bits), so n * LN2_HI is exact
    # for every |n| below 2^16 -- the whole long double exponent range.
    ln2s = split(ln2, (48, 64))
    log2e = split(1 / ln2, (64, 64))

    L = []
    L.append("// GENERATED by tools/gen/gen_libm_tables.py -- do not edit; re-run it.")
    L.append("//")
    L.append("// The bits of 2/pi, 64 to a word, most significant first: word i holds")
    L.append("// bits 64i+1 .. 64i+64 after the binary point. And the long double")
    L.append("// constants no decimal literal states exactly, as hex.")
    L.append("#ifndef TOLIBC_MATH_TABLES_H")
    L.append("#define TOLIBC_MATH_TABLES_H")
    L.append("#include <stdint.h>")
    L.append("")
    L.append("#define M_TWO_OVER_PI_WORDS %d" % WORDS)
    L.append("static const uint64_t m_two_over_pi[M_TWO_OVER_PI_WORDS] = {")
    for i in range(0, WORDS, 3):
        L.append("    " + " ".join("0x%016xull," % w for w in words[i:i + 3]))
    L.append("};")
    L.append("")
    L.append("// pi/2 = PIO2L_HI + PIO2L_LO, each a full 64-bit mantissa.")
    L.append("#define M_PIO2L_HI %s" % ld_hex(pio2[0]))
    L.append("#define M_PIO2L_LO %s" % ld_hex(pio2[1]))
    L.append("// ln 2 = LN2L_HI + LN2L_LO; the first has 48 bits, so n * LN2L_HI is")
    L.append("// exact for |n| < 2^16.")
    L.append("#define M_LN2L_HI %s" % ld_hex(ln2s[0]))
    L.append("#define M_LN2L_LO %s" % ld_hex(ln2s[1]))
    L.append("// log2(e) = LOG2EL_HI + LOG2EL_LO.")
    L.append("#define M_LOG2EL_HI %s" % ld_hex(log2e[0]))
    L.append("#define M_LOG2EL_LO %s" % ld_hex(log2e[1]))
    L.append("")
    L.append("#endif")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if the committed file differs")
    args = ap.parse_args()
    text = generate()
    if args.check:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            print(f"gen_libm_tables: {os.path.relpath(OUT, REPO)} is stale -- re-run the generator")
            return 1
        print("gen_libm_tables: up to date")
        return 0
    with open(OUT, "w") as f:
        f.write(text)
    print(f"gen_libm_tables: wrote {os.path.relpath(OUT, REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
