#!/usr/bin/env python3
"""tools/gen_wcwidth.py -- the East Asian Wide table a grid of cells
measures with: which characters take TWO cells (wcwidth()'s rule).

Writes userland/lib/uwcwidth_table.h, the ranges whose East_Asian_Width
is W (Wide) or F (Fullwidth), merged and sorted for a binary search in
userland/lib/uwcwidth.h. docs/utf8-design.md, "Decided here", 6.

THE SOURCE IS ON THIS MACHINE, NOTHING IS FETCHED: Python's own
`unicodedata` carries the Unicode Character Database's
EastAsianWidth.txt property at the version the interpreter was built
with (printed into the header). It is Unicode, Inc.'s data under the
Unicode License v3, whose notice travels as data/licenses/unicode.txt.
Re-run when a newer Python brings a newer Unicode; the output is
deterministic, so a diff shows exactly what moved.

    python3 tools/gen_wcwidth.py [--out PATH] [--check]

`--check` regenerates in memory and fails if the committed file differs
(a stale table) -- it does NOT fail on an older interpreter's Unicode,
which it reports instead.
"""
import argparse
import os
import sys
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "userland", "lib", "uwcwidth_table.h")


def ranges():
    out, lo, prev = [], None, None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            wide = False
        else:
            wide = unicodedata.east_asian_width(chr(cp)) in ("W", "F")
        if wide and lo is None:
            lo = cp
        if not wide and lo is not None:
            out.append((lo, cp - 1))
            lo = None
        prev = cp
    if lo is not None:
        out.append((lo, prev))
    return out


def render(rs):
    lines = [
        "// GENERATED by tools/gen_wcwidth.py from Unicode %s's East_Asian_Width"
        % unicodedata.unidata_version,
        "// (W and F), Unicode License v3 (data/licenses/unicode.txt). Do not edit:",
        "// re-run the tool. Included by lib/uwcwidth.h only.",
        "#ifndef ULIB_UWCWIDTH_TABLE_H",
        "#define ULIB_UWCWIDTH_TABLE_H",
        "#include <stdint.h>",
        "",
        "static const uint32_t UWCWIDTH_WIDE[][2] = {",
    ]
    for lo, hi in rs:
        lines.append("    { 0x%05X, 0x%05X }," % (lo, hi))
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render(ranges())
    if a.check:
        have = open(a.out).read() if os.path.exists(a.out) else ""
        if have.splitlines()[:1] != text.splitlines()[:1]:
            print("gen_wcwidth: committed table is from another Unicode version; "
                  "not compared (%s here)" % unicodedata.unidata_version)
            return 0
        if have != text:
            print("gen_wcwidth: %s is stale -- re-run tools/gen_wcwidth.py" % a.out)
            return 1
        print("gen_wcwidth: table current (Unicode %s)" % unicodedata.unidata_version)
        return 0
    with open(a.out, "w") as f:
        f.write(text)
    print("gen_wcwidth: %d wide ranges, Unicode %s -> %s"
          % (text.count("{ 0x"), unicodedata.unidata_version, os.path.relpath(a.out, ROOT)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
